using System.Text.RegularExpressions;
using System.Xml.Linq;

namespace ApprovalService.Backend.Checks;

/// <summary>
/// 把仓库约定固化成检查：后端依赖方向、引擎核心的纯净、文件规模、XML 注释开关，三个部分互不引用，任务文件和文档齐全。
/// 规则说明见根目录 AGENTS.md。调用端自己的规则在 client/tests/ApprovalService.Client.Checks。
/// </summary>
internal static partial class ArchitectureChecks
{
    /// <summary>
    /// 运行仓库约定的全部检查。
    /// </summary>
    /// <param name="backendRoot">backend 目录。</param>
    /// <param name="repositoryRoot">仓库根目录。</param>
    /// <param name="check">记录检查结果。</param>
    public static void Run(string backendRoot, string repositoryRoot, Action<string, bool> check)
    {
        string Relative(string path) => Path.GetRelativePath(repositoryRoot, path).Replace('\\', '/');

        CheckLayers(backendRoot, check);

        foreach (var part in new[] { "backend", "client" })
        {
            var partRoot = Path.Combine(repositoryRoot, part);
            var outside = SourceFiles(partRoot, "*.csproj")
                .SelectMany(project => XDocument.Load(project).Descendants("ProjectReference")
                    .Select(reference => Path.GetFullPath(Path.Combine(Path.GetDirectoryName(project)!, (string)reference.Attribute("Include")!))))
                .Where(target => !target.StartsWith(partRoot + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
                .Select(Relative)
                .ToArray();
            check($"{part}/ 的项目只引用本部分的项目" + (outside.Length > 0 ? "：" + string.Join(", ", outside) : ""), outside.Length == 0);
        }

        var frontendRoot = Path.Combine(repositoryRoot, "frontend");
        var frontendOutside = SourceFiles(Path.Combine(frontendRoot, "src"), "*.*")
            .Where(path => Path.GetExtension(path) is ".ts" or ".vue")
            .SelectMany(path => ImportPath().Matches(File.ReadAllText(path))
                .Select(match => match.Groups["path"].Value)
                .Where(import => import.StartsWith('.'))
                .Select(import => Path.GetFullPath(Path.Combine(Path.GetDirectoryName(path)!, import))))
            .Where(target => !target.StartsWith(frontendRoot + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            .Select(Relative)
            .ToArray();
        check("frontend/ 不引用本部分以外的文件" + (frontendOutside.Length > 0 ? "：" + string.Join(", ", frontendOutside) : ""), frontendOutside.Length == 0);

        var props = File.ReadAllText(Path.Combine(backendRoot, "src", "Directory.Build.props"));
        check("后端产品项目强制公开成员写 XML 注释", props.Contains("<GenerateDocumentationFile>true</GenerateDocumentationFile>") && props.Contains("CS1591"));

        var sources = SourceFiles(Path.Combine(backendRoot, "src"), "*.cs").ToArray();
        // 工具生成的文件（EF Core 迁移的 Designer 和快照，开头有 <auto-generated />）不算。
        var large = sources.Where(path => !File.ReadLines(path).Take(3).Any(line => line.Contains("<auto-generated", StringComparison.Ordinal)) && File.ReadLines(path).Count() >= 500)
            .Select(Relative)
            .ToArray();
        check("后端产品源码文件都少于 500 行（工具生成的除外）" + (large.Length > 0 ? "：" + string.Join(", ", large) : ""), large.Length == 0);

        // 代码里不写任务编号（由 DocumentationChecks 检查），这里只核对任务文件本身是否完整。
        var taskFiles = Directory.GetFiles(Path.Combine(repositoryRoot, "docs", "tasks"), "T-*.md");
        var incomplete = taskFiles.Where(path =>
        {
            var text = File.ReadAllText(path);
            return !text.Contains("状态：") || !text.Contains("## 验收标准") || !text.Contains("## 交接记录");
        }).Select(Relative).ToArray();
        check("任务文件都有状态、验收标准和交接记录" + (incomplete.Length > 0 ? "：" + string.Join(", ", incomplete) : ""), incomplete.Length == 0);

        string[] documents =
        [
            "README.md", "AGENTS.md", "CLAUDE.md", "verify.ps1", "backend/README.md", "client/README.md", "frontend/README.md",
            "docs/architecture.md", "docs/contracts.md", "docs/tasks/README.md", "docs/adr/README.md", "docs/design/approval-service-design.html",
        ];
        foreach (var document in documents)
        {
            check($"{document} 存在", File.Exists(Path.Combine(repositoryRoot, document)));
        }

        var agents = File.ReadAllText(Path.Combine(repositoryRoot, "AGENTS.md"));
        check("AGENTS.md 写明了统一验证脚本和三个部分各自的验证命令",
            agents.Contains("verify.ps1")
            && agents.Contains("dotnet build backend/ApprovalService.Backend.slnx")
            && agents.Contains("dotnet run --project backend/tests/ApprovalService.Backend.Checks")
            && agents.Contains("dotnet build client/ApprovalService.Client.slnx")
            && agents.Contains("dotnet run --project client/tests/ApprovalService.Client.Checks")
            && agents.Contains("npm run build"));
    }

    /// <summary>
    /// 后端分层：Contracts ← Engine ← Domain ← Application ← Infrastructure ← Api（docs/architecture.md）。
    /// 引擎核心不引用任何包，不碰数据库、文件、网络和 Web 框架；领域层、应用层不碰 EF Core 和 ASP.NET Core；接口层不直接访问数据库。
    /// </summary>
    /// <param name="backendRoot">backend 目录。</param>
    /// <param name="check">记录检查结果。</param>
    private static void CheckLayers(string backendRoot, Action<string, bool> check)
    {
        var src = Path.Combine(backendRoot, "src");
        string[] References(string name) => XDocument.Load(Path.Combine(src, name, name + ".csproj")).Descendants("ProjectReference")
            .Select(reference => Path.GetFileNameWithoutExtension((string)reference.Attribute("Include")!))
            .Order(StringComparer.Ordinal)
            .ToArray();
        string[] Packages(string name) => XDocument.Load(Path.Combine(src, name, name + ".csproj")).Descendants("PackageReference")
            .Select(reference => (string)reference.Attribute("Include")!)
            .ToArray();
        bool Uses(string name, Regex pattern) => SourceFiles(Path.Combine(src, name), "*.cs").Any(path => pattern.IsMatch(File.ReadAllText(path)));

        check("Contracts 不引用任何项目和包", References("ApprovalService.Contracts").Length == 0 && Packages("ApprovalService.Contracts").Length == 0);
        var allowed = new Dictionary<string, string[]>
        {
            ["ApprovalService.Engine"] = ["ApprovalService.Contracts"],
            ["ApprovalService.Domain"] = ["ApprovalService.Contracts", "ApprovalService.Engine"],
            ["ApprovalService.Application"] = ["ApprovalService.Contracts", "ApprovalService.Domain", "ApprovalService.Engine"],
            ["ApprovalService.Infrastructure"] = ["ApprovalService.Application", "ApprovalService.Contracts", "ApprovalService.Domain", "ApprovalService.Engine"],
            ["ApprovalService.Api"] = ["ApprovalService.Application", "ApprovalService.Contracts", "ApprovalService.Domain", "ApprovalService.Infrastructure"],
        };
        foreach (var (project, expected) in allowed)
        {
            var actual = References(project);
            check($"{project} 只引用下层项目：{string.Join("、", expected)}（实际：{string.Join("、", actual)}）", actual.SequenceEqual(expected));
        }

        check("引擎核心不引用任何包", Packages("ApprovalService.Engine").Length == 0);
        check("引擎核心不碰数据库、文件、网络、Web 框架和依赖注入", !Uses("ApprovalService.Engine", EngineForbidden()));
        check("领域层不引用任何包", Packages("ApprovalService.Domain").Length == 0);
        check("领域层不用 EF Core 和 ASP.NET Core", !Uses("ApprovalService.Domain", LayerForbidden()));
        check("应用层不引用 EF Core、ASP.NET Core 的包",
            !Packages("ApprovalService.Application").Any(item => item.StartsWith("Microsoft.EntityFrameworkCore", StringComparison.Ordinal) || item.StartsWith("Microsoft.AspNetCore", StringComparison.Ordinal)));
        check("应用层不用 EF Core 和 ASP.NET Core", !Uses("ApprovalService.Application", LayerForbidden()));
        check("接口层不直接访问数据库（只通过应用服务）", !Uses("ApprovalService.Api", ApiForbidden()));
    }

    /// <summary>
    /// 列出目录里的源文件，跳过 bin、obj、node_modules。
    /// </summary>
    /// <param name="directory">目录；不存在时返回空。</param>
    /// <param name="pattern">文件名通配符，如 *.cs。</param>
    /// <returns>文件的完整路径。</returns>
    private static IEnumerable<string> SourceFiles(string directory, string pattern)
    {
        if (!Directory.Exists(directory))
        {
            return [];
        }

        var separator = Path.DirectorySeparatorChar;
        return Directory.GetFiles(directory, pattern, SearchOption.AllDirectories)
            .Where(path => !path.Contains($"{separator}bin{separator}") && !path.Contains($"{separator}obj{separator}") && !path.Contains($"{separator}node_modules{separator}"));
    }

    /// <summary>
    /// 引擎核心不能出现的东西：EF Core、ASP.NET Core、.NET 扩展库（依赖注入、配置、日志）、网络、文件读写、数据库连接。
    /// </summary>
    /// <returns>编译好的正则。</returns>
    [GeneratedRegex(@"using (Microsoft\.EntityFrameworkCore|Microsoft\.AspNetCore|Microsoft\.Extensions|System\.Net)\b|\b(HttpClient|DbContext|DbConnection|File|Directory)\.")]
    private static partial Regex EngineForbidden();

    /// <summary>
    /// 领域层、应用层不能出现的 using：EF Core、ASP.NET Core。
    /// </summary>
    /// <returns>编译好的正则。</returns>
    [GeneratedRegex(@"using (Microsoft\.EntityFrameworkCore|Microsoft\.AspNetCore)")]
    private static partial Regex LayerForbidden();

    /// <summary>
    /// 接口层不能出现的数据库访问：EF Core、基础设施层的持久化和仓储命名空间、DbContext。
    /// </summary>
    /// <returns>编译好的正则。</returns>
    [GeneratedRegex(@"using (Microsoft\.EntityFrameworkCore|ApprovalService\.Infrastructure\.(Persistence|Repositories))\b|\bDbContext\b")]
    private static partial Regex ApiForbidden();

    /// <summary>
    /// 前端源码里 import 和 from 后面的路径。
    /// </summary>
    /// <returns>编译好的正则，路径在 path 组。</returns>
    [GeneratedRegex("""(?:from|import)\s+['"](?<path>[^'"]+)['"]""")]
    private static partial Regex ImportPath();
}
